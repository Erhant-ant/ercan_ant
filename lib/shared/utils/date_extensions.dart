extension DateTimeFormatting on DateTime {
  String toTurkishFormat() {
    const months = [
      'Ocak',
      'Şubat',
      'Mart',
      'Nisan',
      'Mayıs',
      'Haziran',
      'Temmuz',
      'Ağustos',
      'Eylül',
      'Ekim',
      'Kasım',
      'Aralık',
    ];
    return '$day ${months[month - 1]} $year';
  }
}
